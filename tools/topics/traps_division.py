print("7 / 2   =", 7 / 2)          # / always gives a float
print("7 // 2  =", 7 // 2)         # // rounds down
print("-7 // 2 =", -7 // 2)        # down means -4; Java's -7 / 2 is -3
print("int(-7 / 2) =", int(-7 / 2))  # cut toward zero, like Java
print("-7 % 2  =", -7 % 2)         # Java's -7 % 2 is -1
print("2 ** 100 =", 2 ** 100)      # no overflow: int grows as needed
